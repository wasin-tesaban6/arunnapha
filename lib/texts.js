// รวมค่าที่บันทึกไว้กับค่าเริ่มต้น
export function mergeTexts(saved) {
  const t = { ...TEXT_DEFAULTS };
  for (const k of Object.keys(TEXT_DEFAULTS)) if (typeof saved?.[k] === 'string' && saved[k].trim()) t[k] = saved[k];
  return t;
}
export function mergeFeatures(saved) {
  return FEATURE_DEFAULTS.map((d, i) => {
    const s = Array.isArray(saved) ? saved[i] || {} : {};
    const pick = (k) => (typeof s[k] === 'string' && s[k].trim() ? s[k] : d[k]);
    return { ...d, title: pick('title'), sub: pick('sub'), text: pick('text'), go: pick('go') };
  });
}
